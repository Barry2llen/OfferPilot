class AIChatHistoryMessage(BaseModel):
    role: str = Field(
        description="Message role. human maps to user, ai maps to assistant, and tool remains tool.",
        examples=["assistant"],
    )
    type: str = Field(
        description="LangChain message type.",
        examples=["ai"],
    )
    content: Any = Field(
        description="Message content. User messages expose display_content visible to the user; hidden attachment bodies are not sent to the frontend.",
        examples=["这份简历的主要优势是项目经历完整、技术栈清晰。"],
    )
    attachments: list[ChatAttachmentRef] | None = Field(
        default=None,
        description="Attachments associated with a user message. Returned only for messages with attachments.",
    )
    reasoning: str | None = Field(
        default=None,
        description="Intermediate reasoning before model inference or tool calls; the frontend should render it collapsed.",
        examples=["我需要先检索最新资料。"],
    )
    reasoning_duration_ms: int | None = Field(
        default=None,
        description="Time spent generating reasoning, in milliseconds. Returned only when reasoning exists.",
        examples=[12000],
    )
    name: str | None = Field(
        default=None,
        description="Message name, usually used for tool messages or named model messages.",
        examples=["web_search_exa"],
    )
    tool_call_id: str | None = Field(
        default=None,
        description="Tool-call ID, returned only for tool messages.",
        examples=["call-001"],
    )
    status: str | None = Field(
        default=None,
        description="Tool-message status, such as success or error.",
        examples=["success"],
    )


class AIChatHistorySummary(BaseModel):
    thread_id: str = Field(
        description="Conversation thread ID.",
        examples=["conversation-001"],
    )
    title: str = Field(
        description="Conversation title, using a truncated first user message by default.",
        examples=["请帮我总结这份简历的优势。"],
    )
    last_message_preview: str = Field(
        description="Preview of the last message.",
        examples=["这份简历的主要优势是项目经历完整、技术栈清晰。"],
    )
    message_count: int = Field(
        description="Number of messages in the latest checkpoint.",
        examples=[2],
    )
    attachment_count: int = Field(
        default=0,
        description="Number of unique attachments associated with the current thread.",
        examples=[1],
    )
    requires_image_input: bool = Field(
        default=False,
        description="Whether the current thread contains image-mode attachments, so the frontend can warn that a text-only model may not use the original images.",
        examples=[True],
    )
    context_compacted: bool = Field(
        default=False,
        description="Whether Supervisor has successfully created a reusable auto-compacted context view for this thread.",
        examples=[True],
    )
    updated_at: datetime = Field(
        description="Creation time of the latest conversation checkpoint.",
        examples=["2026-04-25T20:00:00"],
    )


