class AIChatStreamRequest(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "selection_id": 1,
                    "prompt": "请帮我总结这份简历的优势。",
                    "thread_id": "conversation-001",
                    "file_ids": ["A1B2C3"],
                },
                {
                    "selection_id": 1,
                    "thread_id": "conversation-001",
                    "command": {"type": "retry"},
                },
                {
                    "selection_id": 1,
                    "thread_id": "conversation-001",
                    "command": {
                        "type": "query",
                        "choice": "firstChoice",
                        "note": "按推荐方案继续。",
                    },
                },
            ]
        }
    )

    selection_id: int = Field(
        description="Model selection record ID corresponding to tb_model_selection.id.",
        examples=[1],
    )
    prompt: str | None = Field(
        default=None,
        description="User text message. Optional when attachments are present or when using a retry command.",
        examples=["Summarize the strengths of this resume."],
    )
    thread_id: str | None = Field(
        default=None,
        description="Conversation thread ID. retry and query commands must reuse the thread ID returned by the previous interrupt.",
        examples=["conversation-001"],
    )
    file_ids: list[str] = Field(
        default_factory=list,
        description="List of historical file IDs to reuse in the current request.",
        examples=[["A1B2C3"]],
    )
    command: AIChatCommand | None = Field(
        default=None,
        description="Streaming conversation command. When omitted, the request is treated as prompt; retry resumes a failed interrupt and query resumes a user-choice interrupt.",
        examples=[
            {
                "type": "query",
                "choice": "firstChoice",
                "note": "Continue with the recommended option.",
            }
        ],
    )

    @model_validator(mode="after")
    def validate_stream_command(self) -> "AIChatStreamRequest":
        command_type = self.command.type if self.command else "prompt"

        if command_type in {"retry", "query"}:
            if not self.thread_id:
                raise ValueError(f"thread_id is required when command.type is {command_type}")
            if command_type == "query" and self.command and self.command.choice is None:
                raise ValueError("choice is required when command.type is query")
            return self

        return self
