from datetime import datetime
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator
from schemas.chat_file import ChatAttachmentRef


class AIChatCommand(BaseModel):
    type: Literal["prompt", "continue", "retry", "query"] = Field(
        description=(
            "Streaming conversation command type. prompt starts new input, retry resumes and retries "
            "the last failed interrupt, and query submits a choice from a query-tool interrupt."
        ),
        examples=["query"],
    )
    prompt: str | None = Field(
        default=None,
        description="Text attached to the command. The top-level prompt is used when prompt is omitted; retry and query may omit it.",
        examples=["Continue processing the resume."],
    )
    choice: Literal["firstChoice", "secondChoice", "thirdChoice", "other"] | None = Field(
        default=None,
        description="User choice submitted by a query command. Required only when command.type is query.",
        examples=["firstChoice"],
    )
    note: str | None = Field(
        default=None,
        description="Additional note submitted by a query command; it may be attached to any user choice.",
        examples=["I prefer the lowest-cost option first."],
    )


class AIChatRequest(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "selection_id": 1,
                    "prompt": "请帮我总结这份简历的优势。",
                    "thread_id": "conversation-001",
                    "file_ids": ["A1B2C3"],
                }
            ]
        }
    )

    selection_id: int = Field(
        description="Model selection record ID corresponding to tb_model_selection.id.",
        examples=[1],
    )
    prompt: str | None = Field(
        default=None,
        description="User text message. Optional when attachments are present and required for text-only requests.",
        examples=["Summarize the strengths of this resume."],
    )
    thread_id: str | None = Field(
        default=None,
        description="Conversation thread ID. Reuses a conversation when provided; generated by the server when omitted.",
        examples=["conversation-001"],
    )
    file_ids: list[str] = Field(
        default_factory=list,
        description="List of historical file IDs to reuse in the current request.",
        examples=[["A1B2C3"]],
    )


