function isLocale(value: string | null | undefined): value is Locale {
  return Boolean(value && SUPPORTED_LOCALES.includes(value as Locale));
}

function detectSystemLocale(): Locale {
  if (typeof navigator === "undefined") return "zh-CN";
  const languages = navigator.languages.length > 0 ? navigator.languages : [navigator.language];
  for (const language of languages) {
    const normalized = language.toLowerCase();
    if (normalized.startsWith("en")) return "en-US";
    if (normalized.startsWith("zh")) return "zh-CN";
  }
  return "zh-CN";
}

export function getStoredLocale(): Locale | null {
  if (typeof window === "undefined") return null;
  const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  return isLocale(stored) ? stored : null;
}

export function getInitialLocale(): Locale {
  return getStoredLocale() ?? detectSystemLocale();
}

export function getCurrentLocale(): Locale {
  return isLocale(i18nInstance.resolvedLanguage)
    ? i18nInstance.resolvedLanguage
    : getInitialLocale();
}

export function formatLocaleNumber(
  value: number,
  locale: Locale = getCurrentLocale()
): string {
  return new Intl.NumberFormat(locale).format(value);
}

export function formatLocaleList(
  values: readonly string[],
  locale: Locale = getCurrentLocale()
): string {
  if (typeof Intl !== "undefined" && typeof Intl.ListFormat === "function") {
    return new Intl.ListFormat(locale, {
      style: "short",
      type: "conjunction",
    }).format(values);
  }

  if (locale === "zh-CN") return values.join("、");
  if (values.length < 2) return values.join(", ");
  if (values.length === 2) return `${values[0]} and ${values[1]}`;
  return `${values.slice(0, -1).join(", ")}, and ${values[values.length - 1]}`;
}

function syncDocumentLocale(locale: Locale): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
  document.title = i18nInstance.t("app.documentTitle");
}

void i18nInstance
  .use(initReactI18next)
  .init({
    resources: {
      "zh-CN": { translation: zhCN },
      "en-US": { translation: enUS },
    },
    lng: getInitialLocale(),
    fallbackLng: "zh-CN",
    interpolation: { escapeValue: false },
    returnNull: false,
  });

syncDocumentLocale(getInitialLocale());
i18nInstance.on("initialized", () => syncDocumentLocale(getCurrentLocale()));

i18nInstance.on("languageChanged", (language) => {
  if (isLocale(language)) syncDocumentLocale(language);
});

export async function setLocale(locale: Locale): Promise<void> {
  if (typeof window !== "undefined") {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  }
  await i18nInstance.changeLanguage(locale);
}

